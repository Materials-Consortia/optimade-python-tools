# test_subapp_mounts.py
import urllib.parse

import pytest
from fastapi import FastAPI
from fastapi.testclient import TestClient

from optimade.exceptions import VersionNotSupported
from optimade.server.config import ServerConfig
from optimade.server.create_app import create_app

CONFIG = ServerConfig()


@pytest.fixture
def mounted_client():
    """Mount 3 Optimade APIs with different Mongo databases."""
    parent_app = FastAPI()

    base_url = "http://testserver"

    conf1 = ServerConfig()
    conf1.base_url = f"{base_url}/app1"
    conf1.mongo_database = "optimade_1"
    conf1.provider = {
        "name": "Example 1",
        "description": "Example 1",
        "prefix": "example1",
    }
    app1 = create_app(conf1)
    parent_app.mount("/app1", app1)

    conf2 = ServerConfig()
    conf2.base_url = f"{base_url}/app2"
    conf2.mongo_database = "optimade_2"
    conf2.provider = {
        "name": "Example 2",
        "description": "Example 2",
        "prefix": "example2",
    }
    app2 = create_app(conf2)
    parent_app.mount("/app2", app2)

    conf3 = ServerConfig()
    conf3.base_url = f"{base_url}/idx"
    conf3.mongo_database = "optimade_idx"
    app3 = create_app(conf3, index=True)
    parent_app.mount("/idx", app3)

    return TestClient(parent_app)


@pytest.mark.skipif(
    CONFIG.database_backend.value not in ("mongomock", "mongodb"),
    reason="Requires db-specific config, only MongoDB currently supported.",
)
def test_subapps(mounted_client):
    for app in ["app1", "app2"]:
        r = mounted_client.get(f"/{app}/structures")
        assert r.status_code == 200, f"API not reachable for /{app}"
        response = r.json()
        # Make sure we get at least 10 structures:
        assert len(response["data"]) > 10

        # Make sure the custom providers were picked up:
        prefix = response["meta"]["provider"]["prefix"]
        if app == "app1":
            assert prefix == "example1"
        if app == "app2":
            assert prefix == "example2"

    # the index, make sure links are accessible
    r = mounted_client.get("/idx/links")
    assert r.status_code == 200, "API not reachable for /idx"
    response = r.json()
    assert len(response["data"]) > 5


def _check_links_include_prefix(client: TestClient, prefix: str):
    """Check that the links generated by an API served under `prefix`, without
    an explicitly configured `base_url`, include that prefix."""
    base_url = f"http://testserver{prefix}"

    # /info should advertise the prefixed versioned base URL
    r = client.get(f"{prefix}/info")
    assert r.status_code == 200, r.text
    assert r.json()["data"]["attributes"]["available_api_versions"][0][
        "url"
    ].startswith(f"{base_url}/v1")

    # Pagination links should contain the prefix exactly once
    r = client.get(f"{prefix}/structures?page_limit=2")
    assert r.status_code == 200, r.text
    next_link = r.json()["links"]["next"]
    assert next_link.startswith(f"{base_url}/structures?"), next_link

    # The landing page should link to the prefixed versioned base URL
    r = client.get(f"{prefix}/")
    assert r.status_code == 200, r.text
    assert f"{base_url}/v1/" in r.text

    # Unsupported versions should be caught by the middleware, which
    # requires correctly stripping the prefix from the request path
    with pytest.raises(VersionNotSupported):
        client.get(f"{prefix}/v0/info")

    # `api_hint` should redirect to the prefixed versioned endpoint
    r = client.get(f"{prefix}/structures?api_hint=v1", follow_redirects=False)
    assert r.status_code == 307, r.text
    assert r.headers["location"].startswith(f"{base_url}/v1/structures"), r.headers


@pytest.mark.skipif(
    CONFIG.database_backend.value not in ("mongomock", "mongodb"),
    reason="Requires db-specific config, only MongoDB currently supported.",
)
def test_subapp_links_without_base_url():
    """Check that a mounted sub-application with no `base_url` or `root_path`
    configured generates links including its mount path."""
    parent_app = FastAPI()
    conf = ServerConfig()
    conf.base_url = None
    conf.root_path = None
    parent_app.mount("/app1", create_app(conf))

    _check_links_include_prefix(TestClient(parent_app), "/app1")


@pytest.mark.skipif(
    CONFIG.database_backend.value not in ("mongomock", "mongodb"),
    reason="Requires db-specific config, only MongoDB currently supported.",
)
def test_server_root_path_links_without_base_url():
    """Check that an app served under a root path set by the ASGI server
    (e.g., `uvicorn --root-path`), with no `base_url` configured, generates links
    including the root path."""
    conf = ServerConfig()
    conf.base_url = None
    conf.root_path = None

    _check_links_include_prefix(
        TestClient(create_app(conf), root_path="/optimade"), "/optimade"
    )


@pytest.mark.skipif(
    CONFIG.database_backend.value not in ("mongomock", "mongodb"),
    reason="Requires db-specific config, only MongoDB currently supported.",
)
def test_proxied_root_path_with_base_url():
    """Check an app behind a reverse proxy that strips the path prefix, i.e., with
    the root path set on the ASGI server (e.g., `uvicorn --root-path`) and a public
    `base_url` that differs from the URL the server receives requests on."""
    conf = ServerConfig()
    conf.base_url = "https://example.org/optimade"
    conf.root_path = None
    # Requests arrive without the prefix, as it is stripped by the proxy
    client = TestClient(create_app(conf), root_path="/optimade")

    # Pagination links should use the public base URL, including the prefix once
    r = client.get("/structures?page_limit=2")
    assert r.status_code == 200, r.text
    next_link = r.json()["links"]["next"]
    assert next_link.startswith("https://example.org/optimade/structures?"), next_link

    # Unsupported versions should still be caught by the middleware
    with pytest.raises(VersionNotSupported):
        client.get("/v0/info")

    # `api_hint` should redirect to the versioned endpoint under the prefix
    r = client.get("/structures?api_hint=v1", follow_redirects=False)
    assert r.status_code == 307, r.text
    location = r.headers["location"]
    assert urllib.parse.urlsplit(location).path == "/optimade/v1/structures", location
