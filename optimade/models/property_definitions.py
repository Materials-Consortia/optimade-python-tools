def _nested_definition_from_json_schema(
    schema: dict[str, Any], defs: dict[str, Any], depth: int = 0
) -> dict[str, Any]:
    """Creates one level of a property definition from the given JSON schema."""
    if depth > 16:
        raise ValueError("Cannot create a definition for a recursive property.")

    schema = dict(schema)
    nullable = False

    # Dereference and collapse any unions, allowing only for a single type or null
    while any(key in schema for key in ("$ref", "anyOf", "oneOf", "allOf")):
        if "$ref" in schema:
            inner = defs[schema.pop("$ref").split("/")[-1]]
        else:
            union_key = next(k for k in ("anyOf", "oneOf", "allOf") if k in schema)
            options = schema.pop(union_key)
            non_null_options = [o for o in options if o.get("type") != "null"]
            nullable = nullable or len(non_null_options) != len(options)
            if not non_null_options:
                raise ValueError("Cannot create a definition for a null property.")
            inner = non_null_options[0]
        schema = {**inner, **schema}

    json_type = schema.get("type")
    if isinstance(json_type, list):
        nullable = nullable or "null" in json_type
        json_type = next((t for t in json_type if t != "null"), None)

    if "const" in schema:
        schema.setdefault("enum", [schema["const"]])

    if json_type is None and schema.get("enum"):
        json_type = {str: "string", bool: "boolean", int: "integer", float: "number"}[
            type(schema["enum"][0])
        ]

    if json_type not in _JSON_TYPE_TO_OPTIMADE_TYPE:
        raise ValueError(f"Cannot create a definition for the JSON type {json_type!r}.")

    optimade_type = _JSON_TYPE_TO_OPTIMADE_TYPE[json_type]
    if json_type == "string" and schema.get("format") == "date-time":
        optimade_type = "timestamp"

    definition: dict[str, Any] = {
        "x-optimade-type": optimade_type,
        "x-optimade-unit": "dimensionless"
        if optimade_type in ("integer", "float")
        else "inapplicable",
        "type": [json_type, "null"] if nullable else [json_type],
    }

    for key in ("title", "description", "deprecated", "enum"):
        if key in schema:
            definition[key] = schema[key]

    if isinstance(schema.get("examples"), list):
        definition["examples"] = schema["examples"]

    if schema.get("format") in _JSON_SCHEMA_STRING_FORMATS:
        definition["format"] = schema["format"]

    for key in _JSON_SCHEMA_KEYS_BY_TYPE[json_type]:
        if key in schema:
            definition[key] = schema[key]

    if json_type == "array":
        items = schema.get("items") or next(iter(schema.get("prefixItems", [])), None)
        if not items:
            raise ValueError("Cannot create a definition for a list of unknown items.")
        definition["items"] = _nested_definition_from_json_schema(
            items, defs, depth + 1
        )

    if json_type == "object":
        definition["properties"] = {
            key: _nested_definition_from_json_schema(value, defs, depth + 1)
            for key, value in schema.get("properties", {}).items()
        }
        if not definition["properties"]:
            definition["$comment"] = _UNDESCRIBED_KEYS_COMMENT

    return definition


def property_definition_from_json_schema(
    schema: dict[str, Any],
    name: str,
    entry_type: str | None = None,
    unit: str | None = None,
) -> dict[str, Any]:
    """Creates a property definition from a JSON schema, e.g., one generated by
    a pydantic model, for properties that have no published definition.

    Only the subset of JSON schema that can be expressed in a property definition
    is retained: unions are collapsed onto their first non-null type, and
    restrictions on the length of lists are dropped.
    Numerical values are declared to be dimensionless, unless a `unit` is given
    that is either `dimensionless` or `inapplicable`; other units require
    unit definitions and thus a full definition to be written out.

    Parameters:
        schema: The JSON schema of the property; any references must be
            found under its `$defs`.
        name: The name of the property, including any provider prefix.
        entry_type: The entry type that the property belongs to.
        unit: The unit to use for the outermost level of the definition.

    Raises:
        ValueError: If there is not enough information to create a definition.

    Returns:
        The property definition.

    """
    definition = _nested_definition_from_json_schema(schema, schema.get("$defs", {}))

    if unit in ("dimensionless", "inapplicable"):
        definition["x-optimade-unit"] = unit

    if not definition.get("description"):
        raise ValueError(
            f"Cannot create a full property definition for {name!r} without a description."
        )

    return complete_property_definition(definition, name, entry_type)
