class PropertyDimensions(_DefinitionBaseModel):
    """The `x-optimade-dimensions` field: the dimensions of one or
    multi-dimensional data represented as multiple levels of lists."""

    names: Annotated[
        list[str],
        StrictField(
            description="The names of the dimensions, ordered from the outermost list inwards."
        ),
    ]

    sizes: Annotated[
        list[int | None],
        StrictField(
            description="The fixed length requirements of each dimension; `null` allows for arbitrary-length lists."
        ),
    ]

    compactable: Annotated[
        list[str] | None,
        StrictField(
            description="For each dimension, the compact format that can be used along that dimension, or `no`."
        ),
    ] = None

    @model_validator(mode="after")
    def check_consistent_lengths(self) -> "PropertyDimensions":
        if len(self.names) != len(self.sizes):
            raise ValueError(
                f"`names` and `sizes` must be the same length, not {len(self.names)} and {len(self.sizes)}."
            )
        if self.compactable is not None and len(self.compactable) != len(self.names):
            raise ValueError(
                "If `compactable` is provided, a value MUST be given for each dimension."
            )
        return self


