PROPERTY_DEFINITION_FORMAT = "1.2"
"""The version of the property definition format that is generated by this package,
i.e., the value of `x-optimade-definition->format`."""

META_SCHEMA_URL_TEMPLATE = (
    "https://schemas.optimade.org/meta/v{format}/optimade/{kind}_definition.json"
)

STANDARD_DEFINITIONS_PATH = Path(__file__).parent / "definitions"
"""The directory containing the bundled standard entry type definitions."""

OPTIMADE_TYPE_TO_JSON_TYPE = {
    "string": "string",
    "integer": "integer",
    "float": "number",
    "boolean": "boolean",
    "timestamp": "string",
    "list": "array",
    "dictionary": "object",
}
"""The mapping from OPTIMADE data types (`x-optimade-type`) to the JSON type
that MUST be used as the first element of `type`."""


def get_meta_schema_url(
    definition_format: str = PROPERTY_DEFINITION_FORMAT, kind: str = "property"
) -> str:
    """Returns the `$schema` to use for a definition expressed in the
    given version of the definition format.

    Parameters:
        definition_format: The `MAJOR.MINOR` version of the definition format, as
            found under `x-optimade-definition->format`.
        kind: The kind of definition, e.g., `property` or `physical_unit`.

    """
    return META_SCHEMA_URL_TEMPLATE.format(format=definition_format, kind=kind)


@lru_cache
def _load_standard_entry_type_definition(entry_type: str) -> dict[str, Any] | None:
    path = STANDARD_DEFINITIONS_PATH / f"{entry_type}.json"
    if not path.is_file():
        return None
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def get_standard_entry_type_definition(entry_type: str) -> dict[str, Any] | None:
    """Returns a copy of the standard OPTIMADE definition of the given entry
    type, as published at `https://schemas.optimade.org/defs`, or `None` if the
    entry type is not defined by the supported version of the specification.

    The `properties` key of the returned dictionary maps property names onto
    their property definitions.

    """
    return copy.deepcopy(_load_standard_entry_type_definition(entry_type))


